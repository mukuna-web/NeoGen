"""
Hypothesis and mathematical model representations.
"""

from dataclasses import dataclass, field
from typing import Optional


@dataclass
class CausalRelation:
    """A causal relationship between variables."""
    cause: str
    effect: str
    mechanism: str = ""
    direction: str = "positive"         # "positive" | "negative" | "complex"
    strength: str = "moderate"          # "weak" | "moderate" | "strong"
    evidence: str = ""


@dataclass
class MathModel:
    """A mathematical model / equation proposed by an agent."""
    model_id: str = ""
    name: str = ""
    description: str = ""
    equations: list[str] = field(default_factory=list)       # Symbolic equations (LaTeX or SymPy)
    variables: dict[str, str] = field(default_factory=dict)  # {var_name: description}
    parameters: dict[str, str] = field(default_factory=dict) # {param_name: description}
    assumptions: list[str] = field(default_factory=list)
    domain_of_validity: str = ""
    limitations: list[str] = field(default_factory=list)
    proposed_by: str = ""               # agent_id
    generation: int = 0
    fitness_score: float = 0.0


@dataclass
class Hypothesis:
    """A scientific hypothesis generated by the swarm."""
    hypothesis_id: str = ""
    title: str = ""
    statement: str = ""
    mechanism: str = ""
    supporting_evidence: list[str] = field(default_factory=list)
    contradicting_evidence: list[str] = field(default_factory=list)
    testable_predictions: list[str] = field(default_factory=list)
    math_model: Optional[MathModel] = None
    causal_relations: list[CausalRelation] = field(default_factory=list)
    proposed_by: list[str] = field(default_factory=list)     # agent_ids
    generation: int = 0
    confidence: float = 0.5
    rank: int = 0
    validation_scores: dict[str, float] = field(default_factory=dict)
    status: str = "proposed"            # "proposed" | "debated" | "validated" | "rejected" | "refined"
